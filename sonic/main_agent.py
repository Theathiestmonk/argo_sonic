def run_graph_session(app) -> None:
    """Drives one compiled LangGraph run start-to-finish, handling the
    interrupt/resume protocol with real (or text-mode) speak/listen I/O.
    Each call is a fully self-contained visit (no cross-session order
    carry-over — every terminal path clears table_no/order_items before
    returning to the wake-word loop)."""
    global _current_state

    state = OrderState()
    if FORCED_LOCATION:
        state.table_no = FORCED_LOCATION
        state.trigger_source = "ui"
    _current_state = state

    thread_id = f"main-agent-{uuid_module.uuid4().hex[:8]}"
    config = {"configurable": {"thread_id": thread_id}}
    try:
        result = app.invoke(asdict(state), config)
        while True:
            interrupts = result.get("__interrupt__")
            if not interrupts:
                return
            payload = interrupts[0].value
            prompt_text = payload["prompt"] if isinstance(payload, dict) else str(payload)
            transcript = listen_with_patience(prompt_text)
            resume_value = transcript if transcript is not None else TIMEOUT_SENTINEL
            result = app.invoke(Command(resume=resume_value), config)
    finally:
        # Whether the session ended normally, on an exception, or mid-visit,
        # the dashboard must never keep showing a stale in-progress phase.
        report_phase(None)


