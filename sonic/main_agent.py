def navigate_and_wait(destination: str, timeout_s: float = NAV_TIMEOUT_S) -> bool:
    if SONIC_SKIP_NAV:
        print(f"[nav] test mode — treating {destination!r} as instantly reached, not actually driving")
        return True
    if not voice_nav_enabled():
        print(f"[nav] voice_nav_enabled is off — skipping trip to {destination!r}")
        return False

    cmd = (
        "source /opt/ros/humble/setup.bash && "
        f"source {REPO_ROOT}/install/setup.bash && "
        "export RMW_IMPLEMENTATION=rmw_cyclonedds_cpp && "
        f"python3 {shlex.quote(NAV_BRIDGE_SCRIPT)} --map {shlex.quote(MAP_NAME)} "
        f"--destination {shlex.quote(destination)} --timeout {timeout_s}"
    )
    print(f"[nav] -> {destination!r} (timeout {timeout_s:.0f}s)")
    try:
        result = subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, timeout=timeout_s + 15)
    except subprocess.TimeoutExpired:
        print(f"[nav] {destination!r}: bridge process itself timed out")
        return False

    ok = result.returncode == 0 and "RESULT:SUCCESS" in result.stdout
    print(f"[nav] {destination!r}: {'arrived' if ok else 'FAILED'} (rc={result.returncode})")
    if not ok:
        # nav_bridge.py logs its own diagnosis (action server not found,
        # goal rejected, timeout reason, ...) via plain print() — stdout,
        # not stderr — so stderr alone was silently swallowing the actual
        # reason for every failure, leaving only an uninformative rc=1.
        if result.stdout:
            print(f"[nav] stdout: {result.stdout.strip()[-1000:]}")
        if result.stderr:
            print(f"[nav] stderr: {result.stderr.strip()[-500:]}")
    return ok


def perform_travel_action(state: OrderState, announce_purpose: str, destination: str, **ctx) -> bool:
    # Fire the nav goal immediately, in parallel with the spoken
    # announcement — say() (an LLM call to render the line, TTS synthesis,
    # then blocking playback of the full sentence) used to run to
    # completion BEFORE navigate_and_wait() even started the nav_bridge
    # subprocess, so the robot sat still through the whole announcement.
    # That read as "waits 10 seconds before moving": the wheels were
    # waiting on speech, not on Nav2.
    result: list[bool] = []
    nav_thread = threading.Thread(target=lambda: result.append(navigate_and_wait(destination)))
    nav_thread.start()
    say(announce_purpose, state, **ctx)
    nav_thread.join()
    return result[0] if result else False


