def sarvam_stt(audio: np.ndarray) -> str:
    """English-only, deliberately (see SARVAM_LANGUAGE_CODE) — pinning the
    language_code instead of using "unknown" auto-detect also sidesteps the
    misdetection problem auto-detect had (confidently transcribing into an
    unrelated language on ambiguous/quiet audio)."""
    buf = io.BytesIO()
    with wave.open(buf, "wb") as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(SAMPLE_RATE)
        wf.writeframes(audio.astype(np.int16).tobytes())
    buf.seek(0)

    resp = requests.post(
        SARVAM_STT_URL,
        headers={"api-subscription-key": SARVAM_API_KEY},
        data={"model": SARVAM_STT_MODEL, "language_code": SARVAM_LANGUAGE_CODE},
        files={"file": ("utterance.wav", buf, "audio/wav")},
        timeout=30,
    )
    resp.raise_for_status()
    data = resp.json()
    return (data.get("transcript") or data.get("text") or "").strip()


def sarvam_tts(text: str, language_code: str = SARVAM_LANGUAGE_CODE) -> tuple[np.ndarray, int]:
    resp = requests.post(
        SARVAM_TTS_URL,
        headers={"api-subscription-key": SARVAM_API_KEY, "Content-Type": "application/json"},
        json={
            "inputs": [text],
            "target_language_code": language_code,
            "model": SARVAM_TTS_MODEL,
            "speaker": SARVAM_SPEAKER,
            "pace": SARVAM_TTS_PACE,
        },
        timeout=30,
    )
    resp.raise_for_status()
    data = resp.json()
    audios = data.get("audios") or []
    if not audios:
        raise RuntimeError(f"Sarvam TTS returned no audio: {data}")
    raw = base64.b64decode(audios[0])
    with wave.open(io.BytesIO(raw), "rb") as wf:
        sr = wf.getframerate()
        pcm = np.frombuffer(wf.readframes(wf.getnframes()), dtype=np.int16)
    return pcm, sr


def sarvam_tts_stream(sentences: list, language_code: str = SARVAM_LANGUAGE_CODE) -> bool:
    try:
        import websockets.sync.client as ws_client
    except ImportError:
        return False

    played_any = False
    stream = None
    url = f"{SARVAM_TTS_WS_URL}?model={SARVAM_TTS_MODEL}&send_completion_event=true"
    try:
        with ws_client.connect(url, additional_headers={"Api-Subscription-Key": SARVAM_API_KEY}) as ws:
            ws.send(json.dumps({
                "type": "config",
                "data": {
                    "language_code": language_code,
                    "speaker": SARVAM_SPEAKER,
                    "model": SARVAM_TTS_MODEL,
                    "pace": SARVAM_TTS_PACE,
                    "speech_sample_rate": SARVAM_TTS_SAMPLE_RATE,
                    "output_audio_codec": "linear16",
                },
            }))
            for sentence in sentences:
                ws.send(json.dumps({"type": "text", "data": {"text": sentence}}))
                ws.send(json.dumps({"type": "flush"}))

            stream = sd.OutputStream(samplerate=SARVAM_TTS_SAMPLE_RATE, channels=1, dtype="int16")
            stream.start()

            pending = len(sentences)
            while pending > 0:
                msg = json.loads(ws.recv(timeout=20))
                mtype = msg.get("type")
                if mtype == "audio":
                    pcm = np.frombuffer(base64.b64decode(msg["data"]["audio"]), dtype=np.int16)
                    if pcm.size:
                        stream.write(pcm)
                        played_any = True
                elif mtype == "event" and msg.get("data", {}).get("event_type") == "final":
                    pending -= 1
                elif mtype == "error":
                    print(f"[warn] Sarvam streaming TTS error: {msg}")
                    return played_any
        return True
    except Exception as e:
        print(f"[warn] Sarvam streaming TTS {'ended early' if played_any else 'unavailable, falling back to REST'}: {e}")
        return played_any
    finally:
        if stream is not None:
            stream.stop()
            stream.close()


_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+")


def split_sentences(text: str) -> list:
    parts = _SENTENCE_SPLIT_RE.split(text.strip())
    return [p for p in parts if p]


def _chunk_into_sentences(text_stream):
    """Buffers streamed text deltas (e.g. from LLMClient.chat_stream()) and
    yields each complete sentence as soon as its terminal punctuation AND
    the text after it have arrived — same boundary rule split_sentences()
    uses (_SENTENCE_SPLIT_RE), just applied incrementally so TTS can start
    on sentence 1 while the LLM is still generating sentence 2+, instead of
    waiting for the whole response first."""
    buf = ""
    for delta in text_stream:
        buf += delta
        parts = _SENTENCE_SPLIT_RE.split(buf)
        for complete in parts[:-1]:
            complete = complete.strip()
            if complete:
                yield complete
        buf = parts[-1]
    buf = buf.strip()
    if buf:
        yield buf


def speak_text(text: str) -> None:
    """Low-level: prints, logs the turn, and does TTS playback for an
    already-complete string. Used by the interrupt-prompt path in
    run_graph_session() (listen_with_patience()) — that path needs the full
    rendered text before it can even call interrupt(), so streaming doesn't
    help there (see speak_stream() below, used by say() instead, for
    fire-and-forget lines where it does)."""
    print(f"Sonic: {text}")
    if _current_state is not None:
        _current_state.conversation_history.append({"role": "robot", "text": text})
        db_log_turn(_current_state, "robot", text)
    if TEXT_MODE:
        return

    sentences = split_sentences(text)
    if not sentences:
        return

    if sarvam_tts_stream(sentences):
        return

    audio_queue: "queue.Queue" = queue.Queue(maxsize=2)
    DONE = object()

    def synthesize_worker():
        for sentence in sentences:
            try:
                audio_queue.put(sarvam_tts(sentence))
            except Exception as e:
                print(f"[warn] TTS failed for a chunk: {e}")
        audio_queue.put(DONE)

    worker = threading.Thread(target=synthesize_worker, daemon=True)
    worker.start()

    while True:
        item = audio_queue.get()
        if item is DONE:
            break
        audio, sr = item
        try:
            play_audio(audio, sr)
        except Exception as e:
            print(f"[warn] audio playback failed: {e}")
    worker.join(timeout=1.0)


def speak_stream(sentence_iter) -> None:
    """Streaming sibling of speak_text() — plays each sentence via TTS as
    soon as render_stream() has it, instead of waiting for the whole
    response to finish generating before starting TTS on any of it. Same
    background-thread-synthesizes/main-thread-plays queue shape speak_text()
    already uses for its own REST fallback, just fed by the streaming
    sentence generator instead of a pre-split list — synthesis of sentence
    N+1 can overlap with sentence N still playing. Uses plain sarvam_tts()
    per sentence rather than sarvam_tts_stream() — a single short sentence
    doesn't benefit from a websocket over one REST call, and this avoids
    reopening a websocket per sentence. Logs the full accumulated text as
    ONE conversation_history/db_log_turn entry once the stream ends, same
    one-entry-per-turn convention speak_text() uses (not one per sentence)."""
    spoken_parts = []
    audio_queue: "queue.Queue" = queue.Queue(maxsize=2)
    DONE = object()

    def synthesize_worker():
        for sentence in sentence_iter:
            spoken_parts.append(sentence)
            print(f"Sonic: {sentence}")
            if TEXT_MODE:
                continue
            try:
                audio_queue.put(sarvam_tts(sentence))
            except Exception as e:
                print(f"[warn] TTS failed for a chunk: {e}")
        audio_queue.put(DONE)

    worker = threading.Thread(target=synthesize_worker, daemon=True)
    worker.start()

    if not TEXT_MODE:
        while True:
            item = audio_queue.get()
            if item is DONE:
                break
            audio, sr = item
            try:
                play_audio(audio, sr)
            except Exception as e:
                print(f"[warn] audio playback failed: {e}")
    worker.join(timeout=1.0)

    full_text = " ".join(spoken_parts)
    if _current_state is not None:
        _current_state.conversation_history.append({"role": "robot", "text": full_text})
        db_log_turn(_current_state, "robot", full_text)


def listen(timeout_s: float = SILENCE_ONSET_TIMEOUT_S) -> Optional[str]:
    """Returns the transcript — which may be "" — or None specifically when
    no speech was ever detected within timeout_s (record_utterance's RMS
    gate never triggered: genuine silence). "" means something DID trigger
    the mic (noise, a false RMS blip, a garbled attempt, an STT error) but
    produced no usable text — callers must treat that differently from real
    silence, see listen_with_patience()."""
    if TEXT_MODE:
        try:
            text = input("You: ").strip()
        except EOFError:
            print()
            sys.exit(0)
        if text.lower() in ("quit", "exit"):
            print("Goodbye!")
            sys.exit(0)
        return text or None

    audio = record_utterance(timeout_s)
    if audio is None:
        return None
    try:
        transcript = sarvam_stt(audio)
    except Exception as e:
        print(f"[warn] STT failed: {e}")
        transcript = ""
    print(f"You said: {transcript}")
    return transcript


def listen_with_patience(prompt_text: str) -> Optional[str]:
    """Speak the prompt, then wait through silence rather than bailing
    quickly. Tracks real elapsed wall-clock time (not an assumed fixed
    increment per attempt), and treats two kinds of "no reply" differently:
      - genuine silence (RMS gate never triggered for a full listen window)
        — worth repeating the question, in case they missed it or stepped
        away.
      - something was heard but didn't transcribe to anything usable (a
        stray noise, a false trigger) — NOT treated as silence, and does
        NOT repeat the question; just listens again immediately, since
        talking over someone who's mid-answer is worse than trying again
        quietly.
    Gives up only once SILENCE_GIVEUP_TOTAL_S of total real elapsed time has
    passed with no actual reply. An actual reply at any point returns
    immediately, however long the exchange has been going."""
    speak_text(prompt_text)
    start = time.monotonic()
    while True:
        remaining = SILENCE_GIVEUP_TOTAL_S - (time.monotonic() - start)
        if remaining <= 0:
            return None
        reply = listen(timeout_s=min(SILENCE_ONSET_TIMEOUT_S, remaining))
        if reply:
            return reply
        if reply is None and (time.monotonic() - start) < SILENCE_GIVEUP_TOTAL_S:
            speak_text(prompt_text)


