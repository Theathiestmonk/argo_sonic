YES_NO_EXPECTS = {"yes_no", "yes_no_or_item"}
NEGATIVE_PREFERENCE_WORDS = {"none", "no", "no preference", "nothing", "nope", "not really"}


def get_reply_or_route(state: OrderState, this_node: str, purpose: str, expects: str, **ctx):
    """Returns the extraction outcome dict if the node should keep
    processing it, or None if state.next_node was already set (caller should
    just `return asdict(state)` immediately)."""
    if state.pending_seed is not None:
        outcome = state.pending_seed
        state.pending_seed = None
    else:
        prompt = render(purpose, state, **ctx)
        answer = interrupt({"prompt": prompt})
        if answer == TIMEOUT_SENTINEL:
            say("idle_timeout_farewell", state)
            state.went_idle = True
            state.next_node = "n_respond"
            return None
        state.pending_question = purpose
        outcome = interpret(state, answer, expects)

    if not outcome.get("answers_pending", True):
        last_said = state.conversation_history[-1]["text"] if state.conversation_history else ""
        aside = outcome.get("response_text") or render("redirect_off_topic", state, last_said=last_said)
        speak_text(aside)
        state.next_node = this_node
        return None

    if expects in YES_NO_EXPECTS and outcome.get("yes_no") not in ("yes", "no") and not outcome.get("items"):
        say("yes_no_unclear", state)
        state.next_node = this_node
        return None

    return outcome


