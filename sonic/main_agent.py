"""
main_agent.py — humanized, unified LangGraph voice agent for Sonic (restaurant
service robot). Replaces sonic_agent.py as the one script backend/launcher.py
spawns, for both trigger paths:

    - Dashboard "Take Order" click       -> TABLE_NO/SONIC_ACTION_HINT env vars
                                             set, table+intent already known.
    - Wake word ("Hi Sonic") + speech     -> continuous loop, intent AND table
                                             number (if mentioned) extracted
                                             from what the guest actually says.

Both paths converge on the same LangGraph StateGraph (build_graph() below).
sonic_agent.py is left untouched in the repo as a reference/legacy copy — this
file duplicates whatever infra it needs (DB, audio, STT/TTS, wake word, nav)
rather than importing it, since this is meant to be the only agent maintained
going forward.

Everything the robot says is generated by an LLM call at speak-time (render(),
see the "LLM layer" section) instead of a fixed f-string — this runs against
OpenAI (gpt-4o-mini by default, see LLM_URL/LLM_MODEL). A local Ollama model
on the Jetson was tried and rejected: the robot's own path planner
(ntfields_planner_node.py) already depends on the Jetson's GPU, and a local
LLM competing for that memory is a real risk to navigation, not worth
trading for chat latency — Groq/OpenAI-class cloud inference is already
fast, and cheap enough at this robot's conversation volume not to matter.
Swapping LLM_URL/LLM_MODEL is the only thing needed to point this at a
different provider/model; no node should ever need to change because of it.
Understanding what the guest said is a separate LLM call (extract_slots())
returning one consistent JSON envelope regardless of what's being asked, so a
single multi-item, multi-slot utterance ("4 spicy margherita pizzas and 2
fries") can supply everything in one turn — n_extract_items/route_active_item
below only ever asks for whatever slot is still actually missing.

Scope this round: take_order (and room_service, which maps to the same flow)
is the only intent fully built. Everything else a guest might say during the
wake-word greeting (menu, cutlery, call staff, about, bill, small talk,
delivery) routes to a single stub node (n_stub) that apologizes and hands off
to a human, rather than a full reimplementation — see n_stub. No mid-order
intent-switch-and-resume machinery either (sonic_agent.py had this) since
there's nowhere meaningful to switch to yet; an off-topic reply during any
ask-node just gets a brief redirect back to the same question.

Run modes (same three as sonic_agent.py, plus --test-mode):
    python main_agent.py               real mic/speaker/wake-word loop
    python main_agent.py --text-mode   typed input / printed output
    python main_agent.py --test-mode   real mic/speaker/wake-word loop, but
        every navigate_and_wait() call is an instant no-op arrival instead
        of a real Nav2 trip — everything else (wake word, listening, STT,
        LLM, TTS, ordering, menu browsing, confirm) is exercised for real.
        Combine with --text-mode too for a fully offline NLP-only test.
        Same effect as setting SONIC_SKIP_NAV=1.
    TABLE_NO=<n> SONIC_ACTION_HINT=<order|room_service|bill|deliver> set  ->
        one dispatched Kitchen->Table->Kitchen round trip, no wake word.

Requires OPENAI_API_KEY always (default model gpt-4o-mini — see
LLM_URL/LLM_MODEL to point elsewhere), SARVAM_API_KEY for real voice mode,
and DATABASE_URL (menu is DB-only, same as sonic_agent.py — run seed_db.py
first).
"""

