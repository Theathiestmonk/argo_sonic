def n_intent_classify(state: OrderState) -> dict:
    trace_node("n_intent_classify", state)

    if state.first_turn and FORCED_LOCATION and FORCED_ACTION:
        state.first_turn = False
        state.trigger_source = "ui"
        state.table_no = FORCED_LOCATION
        if FORCED_ACTION in DISPATCH_TAKE_ORDER_ACTIONS:
            state.post_arrival_node = "n_greet_and_ask_order"
            state.next_node = "n_navigate_to_table"
        elif FORCED_ACTION == "deliver":
            state.post_arrival_node = "n_deliver_announce"
            state.next_node = "n_navigate_to_table"
        else:
            state.next_node = "n_stub"
            state.pending_seed = {"stub_intent": FORCED_ACTION}
        return asdict(state)

    state.trigger_source = "voice"
    if state.pending_seed is not None:
        outcome = state.pending_seed
        state.pending_seed = None
    else:
        prompt = render("ask_how_can_i_help", state)
        answer = interrupt({"prompt": prompt})
        if answer == TIMEOUT_SENTINEL:
            say("idle_timeout_farewell", state)
            state.went_idle = True
            state.next_node = "n_respond"
            return asdict(state)
        state.first_turn = False
        state.pending_question = "top-level: how can I help"
        outcome = interpret(state, answer, expects="intent_and_table")

    intent = outcome.get("intent") or "normal_conv"
    if intent == "take_order":
        state.post_arrival_node = "n_greet_and_ask_order"
        state.pending_seed = outcome if outcome.get("items") else None
        state.next_node = "n_navigate_to_table" if state.table_no else "n_ask_table"
    elif intent == "menu":
        state.post_arrival_node = "n_menu_pick_category"
        state.pending_seed = outcome if (outcome.get("items") or outcome.get("category")) else None
        state.next_node = "n_navigate_to_table" if state.table_no else "n_ask_table"
    else:
        state.pending_seed = {"stub_intent": intent}
        state.next_node = "n_stub"
    return asdict(state)


def n_ask_table(state: OrderState) -> dict:
    trace_node("n_ask_table", state)
    purpose = "ask_table_retry" if state.ask_retry else "ask_table"
    outcome = get_reply_or_route(state, "n_ask_table", purpose, expects="table_no")
    if outcome is None:
        return asdict(state)
    if not state.table_no:
        # loop back into THIS SAME ask (retry-flavored) instead of speaking
        # a retry line and then separately re-asking the original question —
        # one spoken line, one listen, every time
        state.ask_retry = True
        state.next_node = "n_ask_table"
        return asdict(state)
    state.ask_retry = False
    state.next_node = "n_navigate_to_table"
    return asdict(state)


def n_navigate_to_table(state: OrderState) -> dict:
    trace_node("n_navigate_to_table", state)
    if state.location_reached:
        state.next_node = state.post_arrival_node
        return asdict(state)
    # table_ref is what actually gets searched for in the waypoints file —
    # the real waypoint name (see table_ref_for_nav), not a guessed/rebuilt
    # string — used identically for the nav_bridge call, the phase report,
    # and the spoken line so all three always agree with each other.
    table_ref = table_ref_for_nav(state.table_no)
    report_phase("heading_to_table", f"Heading to {table_ref}", state.table_no)
    arrived = perform_travel_action(state, "heading_to_table", table_ref, table_ref=table_ref)
    if not arrived:
        say("apology_nav_failed", state)
        state.went_idle = True
        state.next_node = "n_respond"
        return asdict(state)
    state.location_reached = True
    report_phase("arrived", f"Arrived at {table_ref}", state.table_no)
    db_start_session(state)
    state.next_node = state.post_arrival_node
    return asdict(state)


def n_deliver_announce(state: OrderState) -> dict:
    """Dispatched via the table card's "Deliver" button (SONIC_ACTION_HINT=
    deliver) — the food's already on the robot, staged by kitchen staff
    before dispatch; this just announces arrival and waits for the guest to
    physically take it before heading back. ask_retry reused here exactly
    like n_ask_table/n_ask_qty use it — same node, retry-flavored purpose
    on the loop-back rather than repeating the identical "it's here" line."""
    trace_node("n_deliver_announce", state)
    purpose = "delivery_confirm_retry" if state.ask_retry else "delivery_arrived"
    outcome = get_reply_or_route(state, "n_deliver_announce", purpose, expects="yes_no")
    if outcome is None:
        return asdict(state)
    if outcome.get("yes_no") == "yes":
        state.ask_retry = False
        say("delivery_confirmed", state)
        state.went_idle = True
        state.next_node = "n_respond"
        return asdict(state)
    state.ask_retry = True
    state.next_node = "n_deliver_announce"
    return asdict(state)


def n_greet_and_ask_order(state: OrderState) -> dict:
    trace_node("n_greet_and_ask_order", state)
    report_phase("taking_order", "Taking order", state.table_no)
    if state.pending_seed is not None and state.pending_seed.get("items"):
        state.next_node = "n_extract_items"
        return asdict(state)

    prompt = render("arrived_greet_and_ask_order", state)
    answer = interrupt({"prompt": prompt})
    if answer == TIMEOUT_SENTINEL:
        say("idle_timeout_farewell", state)
        state.went_idle = True
        state.next_node = "n_respond"
        return asdict(state)
    state.pending_question = "arrived_greet_and_ask_order"
    outcome = interpret(state, answer, expects="items")
    state.pending_seed = outcome
    state.next_node = "n_extract_items"
    return asdict(state)


def _menu_handoff_to_order(state: OrderState, outcome: dict) -> None:
    """The guest said something like "I'd like to order" while browsing the
    menu — seed n_extract_items exactly the way n_greet_and_ask_order does
    (a pending_seed with an "items" list, or None to fall through to a fresh
    "what would you like" ask if no dish was named yet). table_no/
    location_reached are already set since this only ever runs after
    n_navigate_to_table succeeded."""
    items = outcome.get("items") or []
    state.pending_seed = {"items": items} if items else None
    state.active_menu_category = None
    state.category_intro_said = False
    state.next_node = "n_extract_items"


def _order_handoff_to_menu(state: OrderState, outcome: dict) -> None:
    """Symmetric to _menu_handoff_to_order() — the guest asked about the
    menu ("what do you have", "what's on the menu") while already in the
    order flow instead of naming a dish. Without this, n_extract_items has
    no way to tell that apart from a mis-heard/unmatched dish name, and
    just apologizes and re-asks for a dish forever. Seeds
    n_menu_pick_category the same seeded-fast-path way, so a category they
    already mentioned carries straight through instead of a fresh re-ask."""
    state.pending_seed = outcome if (outcome.get("items") or outcome.get("category")) else None
    state.active_menu_category = None
    state.category_intro_said = False
    state.next_node = "n_menu_pick_category"


def n_menu_pick_category(state: OrderState) -> dict:
    trace_node("n_menu_pick_category", state)
    purpose = "menu_ask_category_retry" if state.ask_retry else "menu_ask_category"
    outcome = get_reply_or_route(state, "n_menu_pick_category", purpose,
                                  expects="menu_category", categories=", ".join(menu_categories()))
    if outcome is None:
        return asdict(state)

    if outcome.get("intent") == "take_order":
        _menu_handoff_to_order(state, outcome)
        return asdict(state)

    if outcome.get("items"):
        item = find_menu_item(outcome["items"][0]["item_name"])
        if item:
            state.active_menu_category = item["category"]
            state.ask_retry = False
            state.category_intro_said = False
            state.next_node = "n_menu_answer_questions"
            return asdict(state)
        # named dish didn't match anything on the menu — fall through to
        # try matching a category instead, same as if none had been named

    matched = find_menu_category(outcome.get("category"))
    if not matched:
        state.ask_retry = True
        state.next_node = "n_menu_pick_category"
        return asdict(state)

    state.ask_retry = False
    state.active_menu_category = matched
    state.category_intro_said = False
    state.next_node = "n_menu_answer_questions"
    return asdict(state)


def n_menu_answer_questions(state: OrderState) -> dict:
    trace_node("n_menu_answer_questions", state)
    items = menu_items_summary(menu_items_by_category(state.active_menu_category))

    if state.category_intro_said:
        purpose = "menu_answer_question"
        question = state.conversation_history[-1]["text"] if state.conversation_history else ""
        ctx = dict(category=state.active_menu_category, items=items, question=question)
    else:
        purpose = "menu_describe_category"
        ctx = dict(category=state.active_menu_category, items=items)

    outcome = get_reply_or_route(state, "n_menu_answer_questions", purpose,
                                  expects="menu_next_step", **ctx)
    if outcome is None:
        return asdict(state)
    state.category_intro_said = True

    if outcome.get("intent") == "take_order":
        _menu_handoff_to_order(state, outcome)
        return asdict(state)

    if outcome.get("category"):
        matched = find_menu_category(outcome["category"])
        if matched and matched != state.active_menu_category:
            state.active_menu_category = matched
            state.category_intro_said = False
            state.next_node = "n_menu_answer_questions"
            return asdict(state)

    if outcome.get("yes_no") == "no":
        say("menu_browse_farewell", state)
        state.went_idle = True
        state.next_node = "n_respond"
        return asdict(state)

    # A genuine follow-up question, not a clean category-switch or a "no" —
    # loop back; next pass answers it (menu_answer_question's {question}
    # context) via the branch above, then re-listens for what's next.
    state.next_node = "n_menu_answer_questions"
    return asdict(state)


def n_extract_items(state: OrderState) -> dict:
    trace_node("n_extract_items", state)
    if state.pending_seed is not None:
        outcome = state.pending_seed
        state.pending_seed = None
    elif state.pending_items:
        outcome = {"items": [state.pending_items.pop(0)], "answers_pending": True}
    else:
        # A prior menu-match failure asks WITH the "sorry, couldn't find X,
        # say it again" purpose directly, instead of speaking that as a
        # standalone aside and then separately re-asking a generic
        # "what would you like" question before ever listening.
        if state.item_attempts > 0:
            outcome = get_reply_or_route(state, "n_extract_items", "item_not_found", expects="items",
                                          item_name=state.last_unmatched_item or "that")
        else:
            outcome = get_reply_or_route(state, "n_extract_items", "ask_what_would_you_like", expects="items")
        if outcome is None:
            return asdict(state)

    if outcome.get("intent") == "menu" and not outcome.get("items"):
        _order_handoff_to_menu(state, outcome)
        return asdict(state)

    items = outcome.get("items") or []
    if not items:
        state.item_attempts += 1
        if state.item_attempts >= 3:
            say("reprompt_unclear_item", state)
            state.went_idle = True
            state.next_node = "n_respond"
            return asdict(state)
        state.last_unmatched_item = "that"
        state.next_node = "n_extract_items"
        return asdict(state)

    first, rest = items[0], items[1:]
    match = find_menu_item(first.get("item_name"))
    if not match:
        state.item_attempts += 1
        if state.item_attempts >= 3:
            say("reprompt_unclear_item", state)
            state.went_idle = True
            state.next_node = "n_respond"
            return asdict(state)
        state.last_unmatched_item = first.get("item_name") or "that"
        state.next_node = "n_extract_items"
        return asdict(state)
    state.item_attempts = 0
    state.last_unmatched_item = None

    if rest:
        state.pending_items.extend(rest)

    state.active_item = {
        "item_id": match["item_id"], "name": match["name"], "category": match["category"],
        "quantity": first.get("quantity"), "preference": first.get("preference"),
        "preference_asked": bool(first.get("preference")),
    }
    state.next_node = route_active_item(state)
    return asdict(state)


def n_ask_qty(state: OrderState) -> dict:
    trace_node("n_ask_qty", state)
    purpose = "ask_quantity_retry" if state.ask_retry else "ask_quantity"
    outcome = get_reply_or_route(state, "n_ask_qty", purpose, expects="quantity",
                                  item_name=state.active_item["name"])
    if outcome is None:
        return asdict(state)
    qty = outcome.get("quantity")
    if not qty:
        state.ask_retry = True
        state.next_node = "n_ask_qty"
        return asdict(state)
    state.ask_retry = False
    state.active_item["quantity"] = qty
    state.next_node = "n_ask_preference" if not state.active_item["preference_asked"] else commit_and_continue(state)
    return asdict(state)


def n_ask_preference(state: OrderState) -> dict:
    trace_node("n_ask_preference", state)
    outcome = get_reply_or_route(state, "n_ask_preference", "ask_preference", expects="preference",
                                  item_name=state.active_item["name"])
    if outcome is None:
        return asdict(state)
    pref = outcome.get("preference")
    if outcome.get("yes_no") == "no" or (pref and str(pref).strip().lower() in NEGATIVE_PREFERENCE_WORDS):
        pref = None
    state.active_item["preference"] = pref
    state.active_item["preference_asked"] = True
    state.next_node = commit_and_continue(state)
    return asdict(state)


def n_ask_anything_else(state: OrderState) -> dict:
    trace_node("n_ask_anything_else", state)
    outcome = get_reply_or_route(state, "n_ask_anything_else", "ask_anything_else", expects="yes_no_or_item")
    if outcome is None:
        return asdict(state)
    if outcome.get("items"):
        state.pending_seed = outcome
        state.next_node = "n_extract_items"
        return asdict(state)
    if outcome.get("yes_no") == "yes" or outcome.get("wants_more") is True:
        state.next_node = "n_extract_items"
        return asdict(state)
    state.next_node = "n_confirm_order"
    return asdict(state)


def n_confirm_order(state: OrderState) -> dict:
    trace_node("n_confirm_order", state)
    outcome = get_reply_or_route(state, "n_confirm_order", "confirm_readback", expects="yes_no",
                                  order_summary=order_summary(state))
    if outcome is None:
        return asdict(state)
    state.next_node = "n_finalize_order" if outcome.get("yes_no") == "yes" else "n_confirm_reject"
    return asdict(state)


def n_confirm_reject(state: OrderState) -> dict:
    trace_node("n_confirm_reject", state)
    outcome = get_reply_or_route(state, "n_confirm_reject", "confirm_reject_choice", expects="cancel_or_change")
    if outcome is None:
        return asdict(state)
    choice = outcome.get("cancel_or_change") or outcome.get("yes_no")
    if choice in ("cancel", "no"):
        state.next_node = "n_cancel_order"
    elif choice in ("change", "yes"):
        state.next_node = "n_edit_order_start"
    else:
        say("cancel_or_change_unclear", state)
        state.next_node = "n_confirm_reject"
    return asdict(state)


def n_cancel_order(state: OrderState) -> dict:
    trace_node("n_cancel_order", state)
    state.order_items = []
    say("cancel_confirmed", state)
    state.went_idle = True
    state.next_node = "n_respond"
    return asdict(state)


def n_edit_order_start(state: OrderState) -> dict:
    trace_node("n_edit_order_start", state)
    if not state.order_items:
        say("nothing_to_edit", state)
        state.went_idle = True
        state.next_node = "n_respond"
        return asdict(state)
    outcome = get_reply_or_route(state, "n_edit_order_start", "edit_ask_target", expects="edit",
                                  order_summary=order_summary(state))
    if outcome is None:
        return asdict(state)
    target = find_order_line(state, outcome.get("edit_target"))
    if not target:
        say("edit_target_not_found", state, item_name=outcome.get("edit_target") or "that item")
        state.next_node = "n_edit_order_start"
        return asdict(state)
    state.edit_target_name = target["name"]
    state.pending_seed = outcome
    state.next_node = "n_edit_apply"
    return asdict(state)


def n_edit_apply(state: OrderState) -> dict:
    trace_node("n_edit_apply", state)
    outcome = state.pending_seed or {}
    state.pending_seed = None
    target = find_order_line(state, state.edit_target_name)
    if not target:
        state.next_node = "n_confirm_order"
        return asdict(state)

    action = outcome.get("edit_action") or "replace"
    value = outcome.get("edit_value")
    if action == "remove":
        state.order_items.remove(target)
        summary = f"removed {target['name']}"
    elif action == "change_qty":
        qty = _safe_int(value)
        if qty:
            target["quantity"] = qty
            summary = f"{target['name']} quantity updated to {qty}"
        else:
            summary = f"kept {target['name']} as is"
    elif action == "change_preference":
        target["preference"] = value
        summary = f"updated {target['name']}'s preference"
    else:
        match = find_menu_item(value)
        if match:
            target.update(item_id=match["item_id"], name=match["name"], category=match["category"])
            summary = f"replaced with {match['name']}"
        else:
            summary = f"couldn't find \"{value or 'that'}\" on the menu, kept {target['name']}"

    say("edit_applied", state, change_summary=summary)
    state.next_node = "n_confirm_order"
    return asdict(state)


def n_finalize_order(state: OrderState) -> dict:
    trace_node("n_finalize_order", state)
    if not state.order_items:
        say("nothing_new_to_confirm", state)
        state.went_idle = True
        state.next_node = "n_respond"
        return asdict(state)
    total = sum(get_item_price(i) * i["quantity"] for i in state.order_items)
    state.order_total = total
    db_place_order(state, state.order_items, total)
    say("closing_thanks", state, order_summary=order_summary(state))
    state.went_idle = True
    state.next_node = "n_respond"
    return asdict(state)


def n_stub(state: OrderState) -> dict:
    trace_node("n_stub", state)
    requested = "that"
    if state.pending_seed:
        requested = state.pending_seed.get("stub_intent") or state.pending_seed.get("intent") or "that"
        state.pending_seed = None
    say("stub_unavailable", state, requested_intent=requested)
    state.went_idle = True
    state.next_node = "n_respond"
    return asdict(state)


def n_respond(state: OrderState) -> dict:
    trace_node("n_respond", state)
    state.pending_question = None
    state.item_attempts = 0
    state.pending_seed = None
    state.ask_retry = False
    state.last_unmatched_item = None
    db_end_session(state)
    state.next_node = "n_return_to_kitchen"
    return asdict(state)


def n_return_to_kitchen(state: OrderState) -> dict:
    trace_node("n_return_to_kitchen", state)
    if state.location_reached:
        report_phase("heading_to_kitchen", "Heading back to kitchen", state.table_no)
        navigate_and_wait("Kitchen")
    state.table_no = None
    state.location_reached = False
    state.next_node = "END"
    return asdict(state)


