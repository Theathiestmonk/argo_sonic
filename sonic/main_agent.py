def main_loop() -> None:
    app = build_graph()

    if TEXT_MODE:
        print("=== main_agent.py (text mode) — no mic, no wake word, no Sarvam calls ===")
        print("Type your first utterance directly (the greeting is simulated).")
        print("Press Enter on a blank line to simulate silence/timeout. Type 'quit' to exit.\n")
        while True:
            run_graph_session(app)
    elif FORCED_LOCATION:
        require_api_keys()
        action_label = FORCED_ACTION or "order"
        print(f"main_agent dispatched: table={FORCED_LOCATION} action={action_label!r} (no wake word needed).")
        navigate_and_wait("Kitchen")
        run_graph_session(app)
    else:
        require_api_keys()
        oww_model = load_wake_word_model()
        print(f"main_agent is listening for the wake word ('{WAKE_WORD_NAME}')...")
        while True:
            wait_for_wake_word(oww_model)
            run_graph_session(app)


