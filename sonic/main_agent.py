def build_extraction_system_prompt(state: OrderState, expects: str) -> str:
    return f"""You are the understanding module for "Sonic", a restaurant robot taking a table's order by \
voice. Read the guest's latest utterance and return ONLY a JSON object (no prose, no markdown fences) with \
exactly this shape:

{EXTRACTION_SCHEMA}

Current stage: {expects} — {EXPECTS_GUIDANCE.get(expects, "")}
What was just asked: {state.pending_question or "nothing yet — this is the opening greeting"}
Order so far: {json.dumps(state.order_items, ensure_ascii=False) if state.order_items else "empty"}

Rules:
- answers_pending=false is a LAST RESORT — the guest is on a real mic/STT pipeline, so transcripts are often \
imperfect (dropped words, odd phrasing, mis-transcribed terms). Set answers_pending=true whenever there is ANY \
reasonable reading of the utterance as addressing what was just asked, even if it's incomplete, oddly \
phrased, or only partially matches — extract whatever you confidently can and leave the rest null rather than \
rejecting the whole utterance. Only set answers_pending=false when the utterance is genuinely about something \
else entirely, or is pure noise/unintelligible with no plausible connection to what was asked.
- Similarly, only leave yes_no null when the utterance truly gives no signal either way — when in doubt \
between a weak yes and null, prefer the yes/no reading over forcing a re-ask.
- Quantity: singular phrasing or "a"/"an" with no explicit number given -> quantity=1. Plural with no \
number given -> quantity=null (the caller will ask). An explicit number always wins.
- If multiple distinct dishes are named in one utterance (e.g. "two pizzas and a coke"), return one entry \
per dish in "items" — never merge them into a single name, never drop any.
- Treat informal affirmatives ("yeah", "yep", "sure", "go ahead") as yes_no="yes" and informal negatives \
("nah", "nope", "not really") as yes_no="no", without requiring the literal words.
- response_text is ONLY for genuine unrelated small talk (a brief, warm, natural reply) — leave it an \
empty string otherwise. Never wrap it in quotation marks.
- Numbers may be spoken as words ("two", "five") — always convert them to actual integers for quantity, \
and to a digit-only string for table_no. Never leave a number as a word in either field.
- intent must be exactly one of the values listed in the schema above, or null — never any other string, \
and never the current stage's name (e.g. don't set intent="yes_no" just because that's the current stage).
- Return valid JSON only, no other text. Every string value must be double-quoted.
"""


def _safe_int(v) -> Optional[int]:
    try:
        n = int(v)
        return n if n > 0 else None
    except (TypeError, ValueError):
        return None


def extract_slots(transcript: str, state: OrderState, expects: str) -> dict:
    system = build_extraction_system_prompt(state, expects)
    history_tail = state.conversation_history[-6:]
    history_text = "\n".join(f"{t['role']}: {t['text']}" for t in history_tail) or "(nothing yet)"
    user = f"Recent conversation:\n{history_text}\n\nLatest utterance: {transcript}"

    result = {}
    try:
        raw = llm.chat(system, user, json_mode=True, temperature=0.1)
        result = json.loads(raw)
    except GroqJSONError as e:
        print(f"[warn] extraction produced invalid JSON, asking it to correct itself: {e}")
        try:
            fix_messages = [
                {"role": "system", "content": system},
                {"role": "user", "content": user},
                {"role": "assistant", "content": e.failed_generation or ""},
                {"role": "user", "content": "That was not valid JSON. Every string value must be double-quoted. "
                                             "Return the corrected JSON object only, no other text."},
            ]
            raw = llm.chat(system, user, json_mode=True, temperature=0.3, messages_override=fix_messages)
            result = json.loads(raw)
        except Exception as e2:
            print(f"[warn] extraction self-correction also failed: {e2}")
            result = {}
    except Exception as e:
        print(f"[warn] extraction call/parse failed: {e}")
        result = {}

    items = []
    for it in (result.get("items") or []):
        if isinstance(it, dict) and it.get("item_name"):
            items.append({
                "item_name": it.get("item_name"),
                "quantity": _safe_int(it.get("quantity")),
                "preference": it.get("preference") or None,
            })

    return {
        "intent": result.get("intent"),
        "table_no": result.get("table_no"),
        "answers_pending": bool(result.get("answers_pending", True)),
        "items": items,
        "quantity": _safe_int(result.get("quantity")),
        "preference": result.get("preference") or None,
        "yes_no": result.get("yes_no"),
        "wants_more": result.get("wants_more"),
        "cancel_or_change": result.get("cancel_or_change"),
        "edit_target": result.get("edit_target"),
        "edit_action": result.get("edit_action"),
        "edit_value": result.get("edit_value"),
        "category": result.get("category") or None,
        "response_text": clean_spoken_text(result.get("response_text")),
    }


def interpret(state: OrderState, transcript: str, expects: str) -> dict:
    state.conversation_history.append({"role": "user", "text": transcript})
    result = extract_slots(transcript, state, expects)
    trace("interpret", transcript=transcript, expects=expects, intent=result.get("intent"),
          answers_pending=result.get("answers_pending"), items=result.get("items"), yes_no=result.get("yes_no"))
    db_log_turn(state, "user", transcript, intent=result.get("intent"), slots=result)
    if result.get("table_no") and not state.table_no:
        state.table_no = str(result["table_no"])
    return result


