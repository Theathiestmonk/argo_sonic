MENU_ITEMS: list = []
MENU_LOOKUP: dict = {}


def load_menu_from_db() -> None:
    global MENU_ITEMS, MENU_LOOKUP
    conn = db()
    if conn is None or DB_LOCATION_ID is None:
        print("No database/location available — menu can't be loaded. Set DATABASE_URL, "
              "then run run_migrations.py and seed_db.py.")
        sys.exit(1)
    try:
        with conn.cursor() as cur:
            cur.execute(
                """SELECT mi.menu_item_id, mi.item_name, mc.name, mi.price, mi.is_available, mi.description
                   FROM menu_items mi
                   LEFT JOIN menu_categories mc ON mi.category_id = mc.category_id
                   WHERE mi.location_id = %s""",
                (DB_LOCATION_ID,),
            )
            rows = cur.fetchall()
            cur.execute(
                """SELECT menu_item_id, alias FROM menu_item_aliases
                   WHERE menu_item_id IN (SELECT menu_item_id FROM menu_items WHERE location_id = %s)""",
                (DB_LOCATION_ID,),
            )
            alias_rows = cur.fetchall()
    except Exception as e:
        print(f"Menu load from DB failed: {e}")
        sys.exit(1)

    if not rows:
        print(f"No menu_items found for location_id={DB_LOCATION_ID} — run seed_db.py first.")
        sys.exit(1)

    aliases_by_item: dict = {}
    for menu_item_id, alias in alias_rows:
        aliases_by_item.setdefault(str(menu_item_id), []).append(alias)

    items = []
    for menu_item_id, item_name, category_name, price, is_available, description in rows:
        items.append({
            "item_id": str(menu_item_id),
            "name": item_name,
            "category": (category_name or "all").strip().lower(),
            "price": float(price),
            "available": is_available,
            "aliases": aliases_by_item.get(str(menu_item_id), []),
            "description": description or "",
        })

    lookup = {}
    for item in items:
        lookup[item["name"].strip().lower()] = item
        for alias in item["aliases"]:
            lookup[alias.strip().lower()] = item

    MENU_ITEMS, MENU_LOOKUP = items, lookup
    print(f"[db] Loaded {len(items)} menu items from Postgres")


def find_menu_item(spoken_name: Optional[str]) -> Optional[dict]:
    if not spoken_name:
        return None
    key = spoken_name.strip().lower()
    if key in MENU_LOOKUP:
        return MENU_LOOKUP[key]
    matches = difflib.get_close_matches(key, MENU_LOOKUP.keys(), n=1, cutoff=0.72)
    return MENU_LOOKUP[matches[0]] if matches else None


def menu_categories() -> list:
    return sorted({i["category"] for i in MENU_ITEMS if i["available"]})


def menu_items_by_category(category: str) -> list:
    return [i for i in MENU_ITEMS if i["available"] and i["category"] == category]


def menu_items_summary(items: list) -> str:
    """Pre-formatted for a render() context value — mirrors order_summary()'s
    convention (a plain readable string, not a raw list of dicts handed to
    .format())."""
    if not items:
        return "nothing available right now"
    return "; ".join(
        f"{i['name']} (${i['price']:.2f})" + (f" — {i['description']}" if i.get("description") else "")
        for i in items
    )


def find_menu_category(spoken_category: Optional[str]) -> Optional[str]:
    """Same fuzzy-match idea as find_menu_item(), but against the live
    category list rather than MENU_LOOKUP — categories aren't a fixed enum
    (see menu_categories()), so this is the only way to turn free text like
    "drinks" or "something spicy" into a real category value."""
    if not spoken_category:
        return None
    cats = menu_categories()
    key = spoken_category.strip().lower()
    for c in cats:
        if c == key:
            return c
    matches = difflib.get_close_matches(key, cats, n=1, cutoff=0.6)
    return matches[0] if matches else None


def get_item_price(order_item: dict) -> float:
    for m in MENU_ITEMS:
        if m["item_id"] == order_item["item_id"]:
            return m["price"]
    return 0.0


def find_order_line(state: OrderState, name: Optional[str]) -> Optional[dict]:
    if not name:
        return None
    match = find_menu_item(name)
    target_name = match["name"] if match else name
    for line in state.order_items:
        if line["name"].lower() == target_name.lower():
            return line
    for line in state.order_items:
        if target_name.lower() in line["name"].lower() or line["name"].lower() in target_name.lower():
            return line
    return None


