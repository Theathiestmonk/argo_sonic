# LLM layer — the "no hardcoded talk" seam. Two call shapes:
#   extract_slots() — understand what the guest said, one consistent schema.
#   render()        — decide what to say next, one call per outgoing line.
# Both go through LLMClient.chat(); swapping to a local model later means
# changing LLMClient's construction, not any node.
# ---------------------------------------------------------------------------

class GroqJSONError(RuntimeError):
    def __init__(self, message: str, failed_generation: Optional[str] = None):
        super().__init__(message)
        self.failed_generation = failed_generation


class LLMClient:
    def __init__(self, base_url: str = LLM_URL, model: str = LLM_MODEL, api_key: Optional[str] = None):
        self.base_url = base_url
        self.model = model
        self.api_key = api_key or LLM_API_KEY

    def chat(self, system: str, user: str, *, json_mode: bool = False, temperature: float = 0.2,
              max_tokens: Optional[int] = None, messages_override: Optional[list] = None) -> str:
        messages = messages_override or [
            {"role": "system", "content": system},
            {"role": "user", "content": user},
        ]
        payload = {"model": self.model, "messages": messages, "temperature": temperature}
        if max_tokens:
            payload["max_tokens"] = max_tokens
        if json_mode:
            payload["response_format"] = {"type": "json_object"}

        last_err = None
        for attempt in range(2):
            payload["temperature"] = temperature + (0.15 if attempt > 0 else 0.0)
            try:
                resp = requests.post(
                    self.base_url,
                    headers={"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"},
                    json=payload,
                    timeout=30,
                )
                if not resp.ok:
                    body_text = resp.text[:2000]
                    failed_generation = None
                    try:
                        failed_generation = resp.json().get("error", {}).get("failed_generation")
                    except Exception:
                        pass
                    if failed_generation:
                        raise GroqJSONError(f"{resp.status_code} {resp.reason}: {body_text[:500]}",
                                             failed_generation=failed_generation)
                    raise RuntimeError(f"{resp.status_code} {resp.reason}: {body_text[:500]}")
                return resp.json()["choices"][0]["message"]["content"]
            except Exception as e:
                last_err = e
                time.sleep(0.5)
        if isinstance(last_err, GroqJSONError):
            raise last_err
        raise RuntimeError(f"LLM call failed after retries: {last_err}")

    def chat_stream(self, system: str, user: str, *, temperature: float = 0.6,
                     max_tokens: Optional[int] = None):
        """Yields text deltas as the LLM streams its completion (SSE), instead
        of blocking for the whole response like chat() does — used only for
        spoken-line generation (render_stream()), never for extraction
        (extract_slots() needs the complete JSON object before it can parse
        anything, so it stays on the blocking chat() above). No retry-on-
        error here unlike chat() — a mid-stream failure is caught by the
        caller (render_stream()) and falls back to chat() entirely, same
        shape as sarvam_tts_stream() falling back to sarvam_tts()."""
        messages = [{"role": "system", "content": system}, {"role": "user", "content": user}]
        payload = {"model": self.model, "messages": messages, "temperature": temperature, "stream": True}
        if max_tokens:
            payload["max_tokens"] = max_tokens
        resp = requests.post(
            self.base_url,
            headers={"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"},
            json=payload,
            stream=True,
            timeout=30,
        )
        resp.raise_for_status()
        for line in resp.iter_lines():
            if not line or not line.startswith(b"data: "):
                continue
            chunk = line[len(b"data: "):]
            if chunk == b"[DONE]":
                return
            delta = json.loads(chunk)["choices"][0]["delta"].get("content")
            if delta:
                yield delta


